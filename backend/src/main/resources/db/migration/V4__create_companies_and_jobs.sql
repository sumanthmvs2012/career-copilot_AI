-- Companies hold the ATS board a scraper reads. ats_type and board_token are NULL for a company typed in by a user on a pasted job.
CREATE TABLE companies (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200)             NOT NULL,
    website     VARCHAR(500),
    careers_url VARCHAR(500),
    ats_type    VARCHAR(30),
    board_token VARCHAR(200),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- A plain index: H2 has no functional index (LOWER(name)), and the migration must run on both H2 and PostgreSQL.
CREATE INDEX idx_companies_name ON companies (name);

-- Jobs come from a scraper or are pasted by a user (source 'manual').
-- created_by_profile_id is set only for manual jobs, so a pasted job is visible only to the user who pasted it.
-- external_id is NULL for manual jobs; repeated NULLs are allowed in the unique constraint.
-- The embedding column is added by the Phase 5 AI migration.
CREATE TABLE jobs (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id            BIGINT,
    created_by_profile_id BIGINT,
    source                VARCHAR(30)              NOT NULL,
    external_id           VARCHAR(200),
    title                 VARCHAR(200)             NOT NULL,
    description           TEXT                     NOT NULL,
    location              VARCHAR(200),
    remote_type           VARCHAR(10),
    source_url            VARCHAR(1000),
    posted_at             TIMESTAMP WITH TIME ZONE,
    scraped_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_jobs_company FOREIGN KEY (company_id) REFERENCES companies (id),
    CONSTRAINT fk_jobs_created_by_profile FOREIGN KEY (created_by_profile_id) REFERENCES profiles (id),
    CONSTRAINT uq_jobs_source_external_id UNIQUE (source, external_id)
);

CREATE INDEX idx_jobs_created_by_profile_id ON jobs (created_by_profile_id);
CREATE INDEX idx_jobs_company_id ON jobs (company_id);

-- A tailored resume points to the job it was tailored for.
ALTER TABLE resumes ADD COLUMN job_id BIGINT;
ALTER TABLE resumes ADD CONSTRAINT fk_resumes_job FOREIGN KEY (job_id) REFERENCES jobs (id);
CREATE INDEX idx_resumes_job_id ON resumes (job_id);
