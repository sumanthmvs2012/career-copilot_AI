-- Resumes belong to a profile. file_path is the storage key, never a URL. Tailored copies point to their base resume.
-- skills, embedding and job_id are added by later migrations (Phase 5 AI migration, jobs migration).
CREATE TABLE resumes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id     BIGINT                   NOT NULL,
    file_path      VARCHAR(500)             NOT NULL,
    file_name      VARCHAR(255)             NOT NULL,
    content_type   VARCHAR(100)             NOT NULL,
    parsed_text    TEXT,
    is_base        BOOLEAN                  NOT NULL DEFAULT TRUE,
    base_resume_id BIGINT,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_resumes_profile FOREIGN KEY (profile_id) REFERENCES profiles (id),
    CONSTRAINT fk_resumes_base_resume FOREIGN KEY (base_resume_id) REFERENCES resumes (id)
);

CREATE INDEX idx_resumes_profile_id ON resumes (profile_id);
