-- Applications link a profile to a job. An agent draft is a row with status 'draft'.
-- A profile can have only one application per job. Deleting a profile deletes its applications;
-- deleting a resume keeps the application and clears resume_id.
CREATE TABLE applications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id   BIGINT                   NOT NULL,
    job_id       BIGINT                   NOT NULL,
    resume_id    BIGINT,
    status       VARCHAR(20)              NOT NULL DEFAULT 'draft',
    cover_letter TEXT,
    submitted_at TIMESTAMP WITH TIME ZONE,
    submitted_by VARCHAR(10)              NOT NULL DEFAULT 'user',
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_applications_profile FOREIGN KEY (profile_id) REFERENCES profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_applications_job FOREIGN KEY (job_id) REFERENCES jobs (id),
    CONSTRAINT fk_applications_resume FOREIGN KEY (resume_id) REFERENCES resumes (id) ON DELETE SET NULL,
    CONSTRAINT uq_applications_profile_job UNIQUE (profile_id, job_id),
    CONSTRAINT ck_applications_status CHECK (status IN ('draft', 'applied', 'interviewing', 'offer', 'rejected', 'withdrawn')),
    CONSTRAINT ck_applications_submitted_by CHECK (submitted_by IN ('user', 'auto'))
);

CREATE INDEX idx_applications_profile_id ON applications (profile_id);
CREATE INDEX idx_applications_job_id ON applications (job_id);
