-- Jobs get a category from a fixed list kept in the application (ARCHITECTURE.md "Job location and category filters").
-- NULL means not classified yet. The jobs.location text column stays as the raw text from the source.
ALTER TABLE jobs ADD COLUMN category VARCHAR(50);

CREATE INDEX idx_jobs_category ON jobs (category);

-- Structured locations: a job can have several. Any of city, state or country may be NULL, but not all three.
CREATE TABLE job_locations (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id  BIGINT       NOT NULL,
    city    VARCHAR(120),
    state   VARCHAR(120),
    country VARCHAR(120),
    CONSTRAINT fk_job_locations_job FOREIGN KEY (job_id) REFERENCES jobs (id) ON DELETE CASCADE,
    CONSTRAINT ck_job_locations_not_empty CHECK (city IS NOT NULL OR state IS NOT NULL OR country IS NOT NULL)
);

CREATE INDEX idx_job_locations_country_state_city ON job_locations (country, state, city);
CREATE INDEX idx_job_locations_job_id ON job_locations (job_id);
