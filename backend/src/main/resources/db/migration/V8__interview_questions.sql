-- Rule-based interview questions, stored per profile and job so repeat calls return the same list.
-- Deleting a profile or job deletes its questions; deleting an application only clears application_id.
CREATE TABLE interview_questions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id     BIGINT                   NOT NULL,
    job_id         BIGINT                   NOT NULL,
    application_id BIGINT,
    question       VARCHAR(1000)            NOT NULL,
    category       VARCHAR(20)              NOT NULL,
    position       INT                      NOT NULL,
    created_at     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_interview_questions_profile FOREIGN KEY (profile_id) REFERENCES profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_questions_job FOREIGN KEY (job_id) REFERENCES jobs (id) ON DELETE CASCADE,
    CONSTRAINT fk_interview_questions_application FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE SET NULL,
    CONSTRAINT ck_interview_questions_category CHECK (category IN ('technical', 'behavioral', 'role', 'company', 'resume_gap'))
);

CREATE INDEX idx_interview_questions_profile_job ON interview_questions (profile_id, job_id);
