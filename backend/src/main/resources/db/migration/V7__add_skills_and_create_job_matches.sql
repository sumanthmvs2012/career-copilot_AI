-- Skills are stored as a JSON array of strings in TEXT columns (null = not extracted yet),
-- so the same SQL runs on PostgreSQL and H2. They may become jsonb with the Phase 5 migration.
ALTER TABLE resumes ADD COLUMN skills TEXT;
ALTER TABLE jobs ADD COLUMN skills TEXT;

-- One saved match result per profile and job. Deleting a profile or job deletes its matches;
-- deleting a resume keeps the match and clears resume_id.
CREATE TABLE job_matches (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id           BIGINT                   NOT NULL,
    job_id               BIGINT                   NOT NULL,
    resume_id            BIGINT,
    score                INT                      NOT NULL,
    matched_skills       TEXT,
    missing_skills       TEXT,
    near_matched_skills  TEXT,
    missing_keywords     TEXT,
    suggested_headline   VARCHAR(200),
    location_fit_status  VARCHAR(20)              NOT NULL DEFAULT 'unknown',
    location_fit_note    VARCHAR(300),
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_job_matches_profile FOREIGN KEY (profile_id) REFERENCES profiles (id) ON DELETE CASCADE,
    CONSTRAINT fk_job_matches_job FOREIGN KEY (job_id) REFERENCES jobs (id) ON DELETE CASCADE,
    CONSTRAINT fk_job_matches_resume FOREIGN KEY (resume_id) REFERENCES resumes (id) ON DELETE SET NULL,
    CONSTRAINT uq_job_matches_profile_job UNIQUE (profile_id, job_id),
    CONSTRAINT ck_job_matches_score CHECK (score BETWEEN 0 AND 100),
    CONSTRAINT ck_job_matches_location_fit_status CHECK (location_fit_status IN ('match', 'partial', 'mismatch', 'unknown'))
);

CREATE INDEX idx_job_matches_profile_id ON job_matches (profile_id);
CREATE INDEX idx_job_matches_job_id ON job_matches (job_id);
