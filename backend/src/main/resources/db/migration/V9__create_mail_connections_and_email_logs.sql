-- Gmail connections (read-only). The refresh token is stored encrypted and cleared on revoke.
-- One active connection per user is enforced in code, not here.
CREATE TABLE mail_connections (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                 BIGINT                   NOT NULL,
    provider                VARCHAR(20)              NOT NULL,
    encrypted_refresh_token TEXT,
    scope                   VARCHAR(200),
    created_at              TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at              TIMESTAMP WITH TIME ZONE,
    last_synced_at          TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_mail_connections_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT ck_mail_connections_provider CHECK (provider IN ('gmail'))
);

CREATE INDEX idx_mail_connections_user_id ON mail_connections (user_id);

-- Employer replies and reminders for an application. No email body or snippet is ever stored.
-- Replies: status 'received'; reminders: status 'new' or 'dismissed'.
CREATE TABLE email_logs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id      BIGINT                   NOT NULL,
    type                VARCHAR(20)              NOT NULL,
    classification      VARCHAR(20),
    subject             VARCHAR(300),
    occurred_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    status              VARCHAR(20)              NOT NULL,
    external_message_id VARCHAR(200),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_email_logs_application FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE CASCADE,
    CONSTRAINT uq_email_logs_application_message UNIQUE (application_id, external_message_id),
    CONSTRAINT ck_email_logs_type CHECK (type IN ('employer_reply', 'reminder')),
    CONSTRAINT ck_email_logs_classification CHECK (classification IS NULL OR classification IN ('rejection', 'interview', 'offer', 'other'))
);

CREATE INDEX idx_email_logs_application_id ON email_logs (application_id);
